import pygame as pg
from pygame.locals import *
from configs import *
from BasicFunction import CalcDist
from time import time
from RRT import RRT
from BSpline import GenerateBSpline


__ObstaclePos = [START, None]
__obstacles = []
__FlagS_RRT = True
__FlagAddObstacle = False

pg.init()
SCREEN = pg.display.set_mode((WIDTH, HEIGHT))
clock = pg.time.Clock()
pg.display.set_caption('S-RRT')


def updateFlagS_RRT():
    global __FlagS_RRT
    __FlagS_RRT = not __FlagS_RRT


def updateResults():
    global __trajectory, __tree, __path, __OptimizedPath, __TraditionalTree, __TraditionalPath
    
    t0 = time()

    # Generate paths using S-RRT
    __tree = RRT(__obstacles, P_GOAL)
    __path = __tree.FindPath()
    __OptimizedPath = __tree.OptimizePath(__path, __obstacles)
    
    # Use control points to generate B-spline curves as motion trajectories
    # Because we are using a third-order B-spline curve, the number of control points is required to be at least 3
    # So when there are only start and end points, add their midpoints as supplementary points
    if len(__OptimizedPath) < 3:
        __OptimizedPath.append((0.5 * (START[0] + GOAL[0]), 0.5 * (START[1] + GOAL[1])))
    __trajectory = GenerateBSpline(__OptimizedPath)

    t1 = time()

    # Generate paths using RRT.
    __TraditionalTree = RRT(__obstacles)
    __TraditionalPath = __TraditionalTree.FindPath()

    t2 = time()
    
    print("Traditional RRT: {}\tnodes, {}\tseconds.".format(len(__TraditionalTree.points),t1 - t0))
    print("S-RRT:           {}\tnodes, {}\tseconds.".format(len(__tree.points),t2 - t1))

updateResults()


def clearObstacles():
    __obstacles.clear()


def updateObstacles():
    global __FlagAddObstacle
    __ObstaclePos[__FlagAddObstacle] = pg.mouse.get_pos()
    if __FlagAddObstacle:
        # Add the big obstacle by dividing it into smaller obstacles and add them
        SmallObsPos = list(__ObstaclePos[0])
        NumOfObs = int(CalcDist(__ObstaclePos[0], __ObstaclePos[1]) / EPS)
        dxObs = (__ObstaclePos[1][0] - __ObstaclePos[0][0]) / NumOfObs
        dyObs = (__ObstaclePos[1][1] - __ObstaclePos[0][1]) / NumOfObs
        for _ in range(NumOfObs):
            __obstacles.append(tuple(SmallObsPos))
            SmallObsPos[0] += dxObs
            SmallObsPos[1] += dyObs
    __FlagAddObstacle = not __FlagAddObstacle


def __DrawTree(tree):
    for point in tree.points:
        pg.draw.circle(SCREEN, GREY, point, 2)
        if point in tree.parent:
            if tree.parent[point] != None:
                pg.draw.aaline(SCREEN, GREY, point, tree.parent[point])


def __DrawPath(path, color):
    for i in range(len(path) - 1):
        pg.draw.aaline(SCREEN, color, path[i], path[i + 1])


def UpdateScreen():
    SCREEN.fill(WHITE)
    
    # Draw start, goal and obstacles
    pg.draw.circle(SCREEN, RED, START, 10)
    pg.draw.circle(SCREEN, RED, GOAL, 10)
    pg.draw.circle(SCREEN, RED, __ObstaclePos[0], 10)
    for obstacle in __obstacles:
        pg.draw.circle(SCREEN, BLACK, obstacle, OBSTACLES_RADIUS)
    
    if __FlagS_RRT:
        # Draw results generated by S-RRT
        __DrawTree(__tree)
        __DrawPath(__path, GREEN)
        __DrawPath(__OptimizedPath, RED)
        for point in __OptimizedPath:
            pg.draw.circle(SCREEN, RED, point, 4)
        __DrawPath(__trajectory, BLUE)
    else:
        # Draw results generated by Traditional RRT
        __DrawTree(__TraditionalTree)
        __DrawPath(__TraditionalPath, GREEN)

    pg.display.flip()
    clock.tick(24)